#!/usr/bin/env node
// Regenerates apps/api/src/iana-tlds.ts, the TLD snapshot of the answer link gate (card 9d060f5c).
//
// USAGE (from the repository root, the package unpacked in an empty directory of its own):
//   npm view tlds version time.modified
//   npm pack tlds@<version> --ignore-scripts && tar -xzf tlds-<version>.tgz -C <dir>
//   node scripts/generate-iana-tlds.mjs <dir>/package/index.json <version> <YYYY-MM-DD>
//
// The package mirrors https://data.iana.org/TLD/tlds-alpha-by-domain.txt, which the fleet's
// egress gate does not reach. Every entry is checked to be one TLD label before it is written;
// IDN TLDs are stored in punycode, as `domainToASCII` returns them, sorted and unique.
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const [source, version, date] = process.argv.slice(2);
if (!source || !/^\d+\.\d+\.\d+$/.test(version ?? "") || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? "")) {
  console.error("usage: node scripts/generate-iana-tlds.mjs <index.json> <version> <YYYY-MM-DD>");
  process.exit(2);
}

const list = JSON.parse(readFileSync(source, "utf8"));
if (!Array.isArray(list) || list.length < 1000) throw new Error(`not a TLD list: ${list?.length} entries`);
const ascii = list.map((tld) => {
  if (typeof tld !== "string" || !/^[\p{L}\p{M}\p{N}-]+$/u.test(tld)) throw new Error(`bad entry ${tld}`);
  const label = domainToASCII(tld);
  if (!/^[a-z0-9-]+$/.test(label)) throw new Error(`not ASCII after domainToASCII: ${tld} -> ${label}`);
  return label;
});
const tlds = [...new Set(ascii)].sort();
if (tlds.length !== list.length) throw new Error("duplicate entries");

const lines = [];
for (let i = 0; i < tlds.length; i += 12) lines.push(`  ${tlds.slice(i, i + 12).join(" ")}`);

writeFileSync(
  "apps/api/src/iana-tlds.ts",
  `/**
 * THE IANA ROOT ZONE'S TOP-LEVEL DOMAINS, A SNAPSHOT (Acropora OS card 9d060f5c, plan v3 section 5.1).
 *
 * A bare domain in an answer ("reefsupplies.ca", no scheme, no www) is a link only if its last label is a real
 * TLD: without the list, "pH 8.2", "manual.pdf" or "Balling.Light" would be addresses too. The snapshot is the
 * npm package \`tlds\` ${version} (published ${date}), which mirrors https://data.iana.org/TLD/tlds-alpha-by-domain.txt;
 * that host is not reachable from the fleet's egress gate, the registry is. IDN TLDs are stored in their
 * punycode (\`xn--\`) form, lower case, as \`domainToASCII\` returns them.
 *
 * A NEW TLD MISSING HERE MAKES A BARE DOMAIN ON IT PASS UNSEEN; a scheme, \`www.\` or \`//\` address is caught
 * without the list. REFRESH every quarter (ICANN delegates and retires TLDs a few times a year): generated by
 * \`node scripts/generate-iana-tlds.mjs\`, whose header gives the three commands; do not edit the list by hand.
 */
export const IANA_TLD_SNAPSHOT = { source: "npm tlds@${version}", date: "${date}" } as const;

export const IANA_TLDS: ReadonlySet<string> = new Set(
  \`
${lines.join("\n")}
\`
    .trim()
    .split(/\\s+/)
);
`
);
console.log(`${tlds.length} TLDs written, tlds@${version} of ${date}`);
